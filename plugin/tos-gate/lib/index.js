// dsh-tos-gate -- TOS reverse-proxy gate plugin (first-party, MIT)
//
// Two responsibilities, neither of which widens the attack surface:
// 1) Mark pages served through the TOS reverse proxy as "local" so the DSH
//    settings panel stays usable;
// 2) Gate the browser session check on a proxy header: only requests carrying
//    the nginx-injected X-Dsh-Gate header (per-install secret) are treated as authenticated.
//    Everything else (direct loopback access, local processes, paths without
//    the header) keeps DSH's native token/cookie check instead of being
//    unconditionally allowed.
//
// nginx only sets X-Dsh-Gate after the per-app auth endpoint returned 204, and
// the value is a **per-install random secret** (generated by postinst, stored in
// $DSH_HOME/gate.secret, never shipped in the package). nginx overrides any
// client-supplied value of the same name, so a local process cannot forge it.

import { readFileSync } from "node:fs";
import { timingSafeEqual } from "node:crypto";

export const name = "@surpasshither/dsh-tos-gate";

const GATE_HEADER = "x-dsh-gate";
const LOG_PREFIX = "[dsh-tos-gate]";

/** browserAuth instances already patched -> original method + reference count. */
const PATCHES = new WeakMap();

function log(message) {
  try {
    console.info(`${LOG_PREFIX} ${message}`);
  } catch {
    /* logging failures must never break startup */
  }
}

function gateSecret() {
  const path = process.env.DSH_GATE_SECRET_FILE
    || (process.env.DSH_HOME ? `${process.env.DSH_HOME}/gate.secret` : "");
  if (!path) return "";
  try {
    return readFileSync(path, "utf8").trim();
  } catch {
    return "";
  }
}

function secretMatches(expected, provided) {
  if (typeof provided !== "string" || expected.length === 0) return false;
  const a = Buffer.from(expected);
  const b = Buffer.from(provided);
  if (a.length !== b.length) return false;
  try {
    return timingSafeEqual(a, b);
  } catch {
    return false;
  }
}

function asBrowserAuth(value) {
  if (typeof value !== "object" || value === null) return undefined;
  return typeof value.isAuthenticated === "function" ? value : undefined;
}

function handle(auth, patched) {
  let released = false;
  return {
    patched,
    restore() {
      if (released) return;
      released = true;
      const entry = PATCHES.get(auth);
      if (entry === undefined) return;
      entry.refs -= 1;
      if (entry.refs > 0) return;
      PATCHES.delete(auth);
      auth.isAuthenticated = entry.original;
    },
  };
}

/**
 * Install the gate: requests whose X-Dsh-Gate equals the per-install secret pass,
 * everything else falls back to the native check.
 * @param connection - host connection service.
 * @returns handle, or undefined when the shape does not match (auth untouched).
 */
function installGate(connection) {
  const auth = asBrowserAuth(connection?.browserAuth);
  if (auth === undefined) return undefined;

  const existing = PATCHES.get(auth);
  if (existing !== undefined) {
    existing.refs += 1;
    return handle(auth, false);
  }

  const original = auth.isAuthenticated;
  PATCHES.set(auth, { original, refs: 1 });
  auth.isAuthenticated = function gatedIsAuthenticated(request, secure) {
    const headers = request?.headers;
    if (secretMatches(gateSecret(), headers?.[GATE_HEADER])) return true;
    return original.call(this, request, secure);
  };
  return handle(auth, true);
}

export function apply(ctx) {
  // Page marker: do not override an injection already made by others.
  ctx.on("webserver/index-inject", (table) => {
    table.push({
      kind: "script",
      placement: "head",
      text: "if(!globalThis.__DSH_TRANSPORT__){globalThis.__DSH_TRANSPORT__={ownsHost:true}}",
    });
  });

  ctx.inject(["connection"], (connectionCtx) => {
    let patch = installGate(connectionCtx.connection);
    log(
      patch === undefined
        ? "connection.browserAuth unavailable: keeping native DSH auth"
        : "TOS gateway trust enabled (only requests with X-Dsh-Gate are allowed)",
    );
    connectionCtx.effect?.(() => () => {
      patch?.restore();
      patch = undefined;
    }, "dsh-tos-gate: restore browser auth");
  });
}
